let x = 5; // asignacion

// operador ==

console.log(x == 6); // false
console.log(x == 5); // true

// operador === compara el valor y el tipo de dato

console.log(x === 5); 
console.log(x === "5");

// operadar != es para comparar si son diferentes

console.log(x != 8);
console.log(x != 5);

// operador !==: va a comparar si son diferentes en valor y tipo de datos

console.log(x !== 5);
console.log(x !== "5");

// operador mayor que >

console.log(x > 10);
console.log(x > 2);

// operador menor que <

console.log(x < 10);
console.log(x < 2);

// operador mayor o igual que >=

console.log(x >= 4);
console.log(x >= 5);
console.log(x >= 6);

// operaror menor o igual que <=

console.log(x <= 4);
console.log(x <= 5);
console.log(x <= 6);