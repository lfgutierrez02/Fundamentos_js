for (let m=1; m <= 10; m++){
    console.log(`Multiplicacion de 7 x ${m} = ${7 * m}`)

}    

// for...of - Recorrer elementos de un arreglo

let nombres =  ["jhon", "Migel", "adriana", "jenifer", "Lizet"];
for(let nombre of nombres){
    console.log(nombre)

}

